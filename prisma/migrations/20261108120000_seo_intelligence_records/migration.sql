CREATE TABLE `SeoIntelligenceRecord` (
  `id` VARCHAR(191) NOT NULL,
  `organizationId` VARCHAR(191) NOT NULL,
  `projectId` VARCHAR(191) NULL,
  `websiteId` VARCHAR(191) NULL,
  `type` VARCHAR(191) NOT NULL,
  `title` VARCHAR(240) NOT NULL,
  `status` VARCHAR(191) NOT NULL DEFAULT 'OPEN',
  `priority` VARCHAR(191) NOT NULL DEFAULT 'MEDIUM',
  `sourceModule` VARCHAR(191) NULL,
  `sourceId` VARCHAR(191) NULL,
  `data` JSON NOT NULL,
  `evidence` JSON NULL,
  `dedupeKey` VARCHAR(191) NULL,
  `createdById` VARCHAR(191) NULL,
  `reviewedById` VARCHAR(191) NULL,
  `reviewedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  INDEX `SeoIntelligenceRecord_organizationId_type_status_updatedAt_idx` (`organizationId`, `type`, `status`, `updatedAt` DESC),
  INDEX `SeoIntelligenceRecord_projectId_type_createdAt_idx` (`projectId`, `type`, `createdAt` DESC),
  INDEX `SeoIntelligenceRecord_websiteId_type_createdAt_idx` (`websiteId`, `type`, `createdAt` DESC),
  INDEX `SeoIntelligenceRecord_sourceModule_sourceId_idx` (`sourceModule`, `sourceId`),
  UNIQUE INDEX `SeoIntelligenceRecord_dedupeKey_key` (`dedupeKey`),
  PRIMARY KEY (`id`),
  CONSTRAINT `SeoIntelligenceRecord_organizationId_fkey` FOREIGN KEY (`organizationId`) REFERENCES `Organization` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `SeoIntelligenceRecord_projectId_fkey` FOREIGN KEY (`projectId`) REFERENCES `Project` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `SeoIntelligenceRecord_websiteId_fkey` FOREIGN KEY (`websiteId`) REFERENCES `Domain` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
